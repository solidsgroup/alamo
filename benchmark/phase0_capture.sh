#!/usr/bin/env bash
# ===========================================================================
# phase0_capture.sh -- local driver for benchmark/phase0_capture.slurm.
#
# Campaign PLAN §12 asks for "one command composes and submits a job; a second
# collects and renders on return". This is that pair. Hand-running the profiler
# at each phase boundary is the failure mode where the figure set gets captured
# twice and then abandoned.
#
# Everything here goes over the ControlMaster tunnel (~/.ssh/config Host `nova`).
# Nothing in this script runs a simulation locally -- kermit is correctness-only
# (campaign PLAN §2).
#
# ACTIONS
#   dryrun            Print every command the job would run. No ssh, no sbatch.
#   push              rsync the working tree's benchmark/ + src/ + decks to NOVA.
#   build             Submit the NOVA build job for BOTH binary variants.
#   submit [DIM ...]  Submit one capture job per dimension (default: 2 3).
#   status            squeue for this user, plus pending-reason for any held job.
#   collect <REMOTE>  rsync one remote artifact dir back under results/figures/.
#
# USAGE
#   bash benchmark/phase0_capture.sh dryrun
#   bash benchmark/phase0_capture.sh push
#   bash benchmark/phase0_capture.sh build
#   bash benchmark/phase0_capture.sh submit 2
#   SERIAL=1 bash benchmark/phase0_capture.sh submit input_copy input input_3d_centre_bore_128_a2
#   bash benchmark/phase0_capture.sh status
#   bash benchmark/phase0_capture.sh collect /work/brunnels/jackplum/alamo/benchmark/_phase0_2d_a100_123456
# ===========================================================================
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"

HOST="${HOST:-nova}"
REMOTE_DIR="${REMOTE_DIR:-/work/brunnels/jackplum/alamo}"
GPU_TYPE="${GPU_TYPE:-a100}"
# Nodes known to fail CUDA init. nova21-gpu-10 aborted two independent jobs
# (11772151, 11772159) at AMReX_GpuDevice.cpp:270 with `CUDA error 3 ...
# initialization error` while nvidia-smi reported a free, idle A100; jobs on
# gpu-12 and gpu-14 ran the same decks and binaries cleanly. Node fault, not a
# deck or script fault. Clear this if the node is repaired.
EXCLUDE_NODES="${EXCLUDE_NODES:-nova21-gpu-10}"
LOCAL_RESULTS="${LOCAL_RESULTS:-${ROOT}/docs/agent_plans/20260727-phase0-baseline/results/figures}"

usage () { sed -n '2,32p' "${BASH_SOURCE[0]}"; exit "${1:-0}"; }
ACTION="${1:-}"; shift || true
[ -z "${ACTION}" ] && usage 0

ssh_nova () { ssh -o BatchMode=yes -o ConnectTimeout=15 "${HOST}" "$@"; }

case "${ACTION}" in

  dryrun)
    DRYRUN=1 DIM="${DIM:-2}" GPU_TYPE="${GPU_TYPE}" bash benchmark/phase0_capture.slurm
    ;;

  push)
    # Provenance: the remote checkout's own git metadata describes whatever was
    # cloned there, NOT the working tree being pushed over it. The metrics ledger
    # is keyed on commit_sha (campaign §12), so stamp the real source revision
    # into a file that travels with the code and gets read back by the env leg.
    # Campaign PLAN v2 §5.1 (precondition P2): a ledger row keyed on commit_sha
    # cannot identify a dirty-tree measurement, and the branch cannot bisect or
    # reproduce it. A dirty count is not enough -- 574 dirty files including
    # Flame.* was the state the first baseline was captured from.
    #
    # Policy here is RECORD, not REFUSE. Refusing would make the harness
    # unusable exactly when it is most needed (the working tree carries the
    # changes under test). Instead every capture now ships:
    #   _pushed_rev.txt       provenance header, including tree_hash
    #   _pushed_tree.diff     full diff of tracked modifications vs HEAD
    #   _pushed_manifest.tsv  sha256 of every file actually shipped
    # tree_hash is the ledger's second key and is content-derived, so two
    # captures from the same source get the same key whether or not it is
    # committed.
    #
    # STRICT=1 restores the refuse-on-dirty behaviour for release captures.
    # These three files are generated by this action. A second push must not
    # report the first push's provenance as new source dirt, or the same payload
    # receives a different key merely because it was pushed twice.
    DIRTY_N=$(git status --porcelain -- . \
      ':(exclude)benchmark/_pushed_rev.txt' \
      ':(exclude)benchmark/_pushed_tree.diff' \
      ':(exclude)benchmark/_pushed_manifest.tsv' | wc -l)
    if [ "${STRICT:-0}" = "1" ] && [ "${DIRTY_N}" -ne 0 ]; then
      echo "STRICT=1 and the tree is dirty (${DIRTY_N} files). Refusing to push." >&2
      echo "Commit, stash, or drop STRICT to capture with a recorded manifest." >&2
      exit 3
    fi

    git diff HEAD > benchmark/_pushed_tree.diff 2>/dev/null || : > benchmark/_pushed_tree.diff

    # Manifest over the payload rsync ships below, plus untracked BMP deck
    # assets. The three derived _pushed_* provenance files are excluded: a
    # manifest cannot hash itself, and tree_hash already includes the diff and
    # manifest explicitly. Sorted so the hash is order-independent.
    {
      find ./benchmark ./src -type f \
           ! -path '*/_phase0_*' ! -path '*/_two_rank_probe_*' \
           ! -path '*/_a100_gate_*' ! -path '*/baseline_runs/*' \
           ! -path '*/__pycache__/*' ! -name '_pushed_rev.txt' \
           ! -name '_pushed_tree.diff' ! -name '_pushed_manifest.tsv' -print0
      find . -maxdepth 1 \( -name 'input*' -o -name '*.bmp' -o -name 'configure' \
           -o -name 'Makefile' \) -type f -print0
    } 2>/dev/null | sort -z | xargs -0 sha256sum 2>/dev/null \
      | awk '{print $1"\t"$2}' > benchmark/_pushed_manifest.tsv

    # tree_hash: HEAD + the diff + the manifest. Any change to anything shipped
    # moves it, harness included.
    TREE_HASH=$( { git rev-parse HEAD
                   sha256sum benchmark/_pushed_tree.diff | cut -d' ' -f1
                   sha256sum benchmark/_pushed_manifest.tsv | cut -d' ' -f1
                 } | sha256sum | cut -c1-16 )
    # src_hash: the ./src subset of the manifest only. This is what identifies a
    # BINARY. Editing the harness moves tree_hash but not src_hash, so a capture
    # whose slurm script changed after the build is still traceable to the
    # source it actually ran -- without which every harness tweak would look
    # like it invalidated the binaries.
    SRC_HASH=$(awk -F'\t' '$2 ~ /^\.\/src\//' benchmark/_pushed_manifest.tsv \
               | sha256sum | cut -c1-16)
    {
      echo "pushed_from_host=$(hostname)"
      echo "pushed_at=$(date -Is)"
      echo "local_branch=$(git rev-parse --abbrev-ref HEAD)"
      echo "local_head=$(git rev-parse HEAD)"
      echo "local_dirty_files=${DIRTY_N}"
      echo "tree_hash=${TREE_HASH}"
      echo "src_hash=${SRC_HASH}"
      echo "manifest_files=$(wc -l < benchmark/_pushed_manifest.tsv)"
      echo "# tree_hash = sha256(HEAD + sha256(_pushed_tree.diff) +"
      echo "#                    sha256(_pushed_manifest.tsv)), first 16 hex."
      echo "# LEDGER KEY is (local_head, tree_hash, case, n_ranks, device,"
      echo "# build_config) per PLAN v2 §14.2. local_head ALONE is not a key"
      echo "# whenever local_dirty_files != 0."
    } > benchmark/_pushed_rev.txt
    echo "=== rsync -> ${HOST}:${REMOTE_DIR}"
    rsync -az --info=stats1 \
      --exclude '.git' --exclude 'bin' --exclude 'ext' --exclude '__pycache__' \
      --exclude 'benchmark/_phase0_*' --exclude 'benchmark/_two_rank_probe_*' \
      --exclude 'benchmark/_a100_gate_*' --exclude 'benchmark/baseline_runs' \
      ./benchmark ./src ./input* ./configure ./Makefile \
      "${HOST}:${REMOTE_DIR}/"
    # Deck assets. input_copy's eta IC is blur5_rod_and_tube.bmp, which is
    # untracked locally and was NOT on NOVA -- the deck aborts at InitData
    # without it. Push every BMP rather than tracking the dependency by hand.
    rsync -az --info=stats1 ./*.bmp "${HOST}:${REMOTE_DIR}/" 2>/dev/null || true
    echo "--- provenance pushed:"; cat benchmark/_pushed_rev.txt
    echo "NOTE: bin/ and ext/ are deliberately not pushed -- build on NOVA."
    ;;

  build)
    # ARCHES defaults to 80 (A100) only. Each (dim x arch x variant) is a full
    # nvcc build and build_alamo_nova.sh's job carries a 4 h limit, so building
    # sm_90 as well doubles the work for a GPU this round does not target.
    BUILD_ARCHES="${ARCHES:-80}"
    BUILD_DIMS="${DIMS:-2 3}"
    BUILD_VARIANTS="${VARIANTS:-profile plain}"
    echo "=== submitting NOVA build: dims='${BUILD_DIMS}' arches='${BUILD_ARCHES}' variants='${BUILD_VARIANTS}'"
    # SKIP_GIT=1: the pushed tree is authoritative. See build_alamo_nova.sh.
    ssh_nova "cd ${REMOTE_DIR} && SKIP_GIT=1 VARIANTS='${BUILD_VARIANTS}' DIMS='${BUILD_DIMS}' ARCHES='${BUILD_ARCHES}' sh benchmark/build_alamo_nova.sh"
    ;;

  submit)
    # Decks, primary first. input_copy is the production-condition deck (user
    # ruling 2026-07-27); input and the 3D centre-bore case are kept alongside.
    DECKS=("$@")
    [ "${#DECKS[@]}" -eq 0 ] && DECKS=(input_copy input input_3d_centre_bore_128_a2)
    NEXT_DEPENDENCY="${DEPENDENCY:-}"
    for d in "${DECKS[@]}"; do
      echo "=== submit DECK=${d} GPU_TYPE=${GPU_TYPE} LEGS='${LEGS:-default}'"
      DEPENDENCY_OPT=""
      if [ -n "${NEXT_DEPENDENCY}" ]; then
        DEPENDENCY_OPT="--dependency=afterok:${NEXT_DEPENDENCY}"
      fi
      JOB_ID=$(ssh_nova "cd ${REMOTE_DIR} && sbatch --parsable --gres=gpu:${GPU_TYPE}:1 \
                  ${EXCLUDE_NODES:+--exclude=${EXCLUDE_NODES}} \
                  ${DEPENDENCY_OPT} \
                  --export=ALL,DECK=${d},GPU_TYPE=${GPU_TYPE}${LEGS:+,LEGS='${LEGS}'}${SMOOTH_STEP:+,SMOOTH_STEP=${SMOOTH_STEP}} \
                  benchmark/phase0_capture.slurm")
      echo "${JOB_ID}"
      if [ "${SERIAL:-0}" = "1" ]; then
        NEXT_DEPENDENCY="${JOB_ID}"
      fi
    done
    echo "Record the job ids. Do not block on the queue (campaign §2)."
    ;;

  status)
    ssh_nova 'squeue -u $USER -o "%.10i %.12j %.8T %.10M %.20R" 2>/dev/null'
    echo "--- pending reasons (if any)"
    ssh_nova "cd ${REMOTE_DIR} && bash benchmark/slurm_pending_reason.sh 2>/dev/null | head -20" || true
    ;;

  collect)
    REMOTE="${1:-}"; [ -z "${REMOTE}" ] && { echo "collect needs a remote artifact dir"; usage 2; }
    NAME="$(basename "${REMOTE}")"
    mkdir -p "${LOCAL_RESULTS}/${NAME}"
    echo "=== rsync ${HOST}:${REMOTE} -> ${LOCAL_RESULTS}/${NAME}"
    # Traces are large; CSVs and logs are what the figure set is built from.
    # Keep raw profiler reports and plot/checkpoint trees on NOVA unless the
    # caller explicitly requests them.  The old command copied everything
    # despite this comment, which can silently pull multi-gigabyte traces and
    # dozens of repeated timing plot trees into the worktree.
    COLLECT_FILTERS=(
      --exclude='*.nsys-rep'
      --exclude='*.ncu-rep'
      --exclude='*.sqlite'
      --exclude='cuda_gpu_trace*.csv'
      --exclude='plot*/'
    )
    if [ "${RAW:-0}" = "1" ]; then
      COLLECT_FILTERS=()
    fi
    rsync -az --info=stats1 "${COLLECT_FILTERS[@]}" \
      "${HOST}:${REMOTE}/" "${LOCAL_RESULTS}/${NAME}/"
    if [ "${RAW:-0}" != "1" ]; then
      echo "=== raw profiler reports and plot trees retained at ${HOST}:${REMOTE}"
      echo "    rerun with RAW=1 only when local raw artifacts are required"
    fi
    echo "=== collected:"
    find "${LOCAL_RESULTS}/${NAME}" -maxdepth 2 -type f | head -40
    ;;

  *) echo "unknown action '${ACTION}'"; usage 2 ;;
esac
